"""Dependency inversion ports for the assistant domain."""

from __future__ import annotations

from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Iterable, Mapping, Protocol

from chrom_platform.task_core.service import OperationContext

from .schemas import (
    AgentRun, Attempt, Conversation, Message, PendingConfirmationBinding,
    ToolCall, ToolCallDraft,
)


class AssistantUnitOfWork(Protocol):
    def transaction(self, session: object | None = None) -> AbstractContextManager[object]: ...


class AssistantRepository(Protocol):
    """Repository methods used by the service.

    Implementations must lock the conversation row in ``lock_conversation``
    and must never commit or close a caller-owned session.
    """

    def transaction(self, session: object | None = None) -> AbstractContextManager[object]: ...
    def lock_conversation(self, session: object, conversation_id: str) -> Conversation | None: ...
    def get_conversation(self, session: object, conversation_id: str) -> Conversation | None: ...
    def list_conversations(self, session: object, *, project_id: str | None, owner_id: str, archived: bool | None, q: str | None, limit: int) -> list[Conversation]: ...
    def save_conversation(self, session: object, value: Conversation) -> None: ...
    def get_message_by_client_id(self, session: object, conversation_id: str, client_message_id: str) -> Message | None: ...
    def list_messages(self, session: object, conversation_id: str, *, limit: int, before: str | None = None) -> list[Message]: ...
    def save_message(self, session: object, value: Message) -> None: ...
    def save_client_message_id(self, session: object, conversation_id: str, client_message_id: str, message_id: str) -> None: ...
    def save_message_payload_hash(self, session: object, message_id: str, payload_hash: str) -> None: ...
    def get_message_payload_hash(self, session: object, message_id: str) -> str | None: ...
    def save_run(self, session: object, value: AgentRun) -> None: ...
    def get_run(self, session: object, run_id: str) -> AgentRun | None: ...
    def list_runs(self, session: object, conversation_id: str, *, limit: int) -> list[AgentRun]: ...
    def save_attempt(self, session: object, value: Attempt) -> None: ...
    def get_attempt(self, session: object, agent_run_id: str, attempt: int) -> Attempt | None: ...
    def save_tool_call(self, session: object, value: ToolCall) -> None: ...
    def get_tool_call(self, session: object, tool_call_id: str) -> ToolCall | None: ...
    def list_tool_calls(self, session: object, *, run_id: str | None = None, conversation_id: str | None = None, limit: int) -> list[ToolCall]: ...


class AssistantAccessPort(Protocol):
    def ensure_project_access(self, ctx: OperationContext, project_id: str, *, permission: str) -> None: ...


class BusinessApplicationServicePort(Protocol):
    """A typed business service owned by M2/M3.

    The assistant may validate and invoke this port only.  It cannot access a
    module repository, create Confirmation resources, or submit arbitrary jobs.
    """

    def validate(self, ctx: OperationContext, *, tool_name: str, arguments: Mapping[str, Any], resource_ref: Any = None) -> Any: ...
    def execute(self, ctx: OperationContext, *, tool_name: str, arguments: Mapping[str, Any], resource_ref: Any = None, confirmation_id: str | None = None) -> Any: ...


class ConfirmationValidationPort(Protocol):
    def validate_binding(self, ctx: OperationContext, confirmation_id: str, binding: PendingConfirmationBinding) -> None: ...


class AssistantToolAuthorizationPort(Protocol):
    def authorize(self, ctx: OperationContext, *, tool_name: str, permission: str) -> None: ...


class LLMProviderAdapter(Protocol):
    """Provider boundary used by the runtime.

    Implementations receive a public configuration snapshot only.  A worker
    must never pass a database session, a raw secret, or client supplied
    framework history through this port.
    """

    def complete(self, *, config: object, messages: Iterable[Mapping[str, Any]], tools: Iterable[Mapping[str, Any]] = (), response_schema: Mapping[str, Any] | None = None, timeout_seconds: float | None = None) -> object: ...

    def stream(self, *, config: object, messages: Iterable[Mapping[str, Any]], tools: Iterable[Mapping[str, Any]] = (), response_schema: Mapping[str, Any] | None = None, timeout_seconds: float | None = None) -> Iterable[object]: ...


class AssistantHistoryPort(Protocol):
    """Trusted server-side history loader for a run."""

    def load_history(self, run_id: str, *, attempt: int | None = None) -> Iterable[Mapping[str, Any]]: ...


class ToolExecutionLedgerPort(Protocol):
    def get(self, operation_key: str) -> object | None: ...
    def put(self, operation_key: str, value: object) -> object: ...


class AgentExecutionStore(Protocol):
    """Short transaction boundary for Agent Worker claim/fencing/finish."""

    def load_run(self, run_id: str) -> object | None: ...
    def claim(self, *, run_id: str, attempt: int, dispatch_id: str, lease_seconds: int) -> object | None: ...
    def is_cancel_requested(self, run_id: str) -> bool: ...
    def finish(self, *, run_id: str, attempt: int, dispatch_id: str, fencing_token: int, status: str, result: object | None = None, error: Mapping[str, Any] | None = None) -> object: ...


class AssistantRuntimeEventPort(Protocol):
    def append(self, stream_type: str, stream_id: str, event_type: str, data: Mapping[str, Any], *, agent_run_id: str | None = None, schema_version: str = "1.0", timestamp: datetime | None = None) -> object: ...


