"""Ports owned by the training module.

No port accepts source code or a path.  Scientific implementations are
selected by a server-side template registry and are never resolved from a
request field.
"""

from __future__ import annotations

from collections.abc import Sequence
from contextlib import AbstractContextManager
from typing import Any, Protocol

from .schemas import (
    CandidateResult,
    EvaluationProtocol,
    Experiment,
    TrainingCandidate,
    TrainingExperimentSpec,
    TrainingJob,
    TrainingTemplate,
    WorkerMessage,
    ExperimentMetrics,
    TrainingArtifact,
    TrainingEvent,
    LogEntry,
)


class TemplateHandler(Protocol):
    def __call__(self, spec: TrainingExperimentSpec, *, attempt: int) -> CandidateResult: ...


class TrainingTemplateRegistry(Protocol):
    def list(self, *, task_type: str | None = None) -> Sequence[TrainingTemplate]: ...
    def get(self, template_id: str, version: str) -> TrainingTemplate | None: ...
    def handler(self, template_id: str, version: str) -> TemplateHandler | None: ...


class DataVersionPort(Protocol):
    def get(self, project_id: str, version_id: str) -> object | None: ...
    def reference(self, project_id: str, version_id: str, reference_id: str) -> object: ...


class FeatureVersionPort(Protocol):
    def get(self, version_id: str) -> object | None: ...


class EvaluationProtocolPort(Protocol):
    def get(self, protocol_id: str, version: str) -> EvaluationProtocol | object | None: ...


class ConfirmationPort(Protocol):
    def consume(self, *, confirmation_id: str, project_id: str, resource_ref: dict[str, str], action: str, revision: int, config_hash: str, result_ref: dict[str, str], actor_id: str | None = None) -> object: ...


class CandidateRegistrationPort(Protocol):
    def register_candidate(self, *, project_id: str, experiment: Experiment, result: CandidateResult) -> TrainingCandidate: ...


class TrainingRepository(Protocol):
    def transaction(self) -> AbstractContextManager[object]: ...
    def save_experiment(self, value: Experiment) -> Experiment: ...
    def get_experiment(self, project_id: str, experiment_id: str) -> Experiment | None: ...
    def list_experiments(self, project_id: str, *, task_type: str | None = None, status: str | None = None) -> Sequence[Experiment]: ...
    def create_submission(self, *, experiment: Experiment, confirmation_id: str, actor_id: str, idempotency_key: str | None) -> tuple[TrainingJob, bool]: ...
    def get_submission_replay(self, *, experiment: Experiment, confirmation_id: str, actor_id: str, idempotency_key: str) -> TrainingJob | None: ...
    def get_job(self, job_id: str) -> TrainingJob | None: ...
    def save_job(self, value: TrainingJob) -> TrainingJob: ...
    def get_outbox(self, dispatch_id: str) -> object | None: ...
    def save_outbox(self, value: object) -> object: ...
    def cancel_outbox(self, dispatch_id: str) -> bool: ...
    def claim_outbox(self, message: WorkerMessage, *, owner: str) -> object | None: ...
    def claim_next_outbox(self, *, owner: str) -> object | None: ...
    def recover_outbox(self, message: WorkerMessage, *, owner: str) -> object | None: ...
    def ack_outbox(self, lease: object) -> bool: ...
    def retry_outbox(self, lease: object) -> bool: ...
    def list_audits(self, project_id: str) -> Sequence[object]: ...
    def save_candidate(self, value: TrainingCandidate) -> TrainingCandidate: ...
    def get_candidate(self, candidate_id: str) -> TrainingCandidate | None: ...

    # Optional read ports for durable execution telemetry.  Implementations
    # may back these with the shared event/log/artifact stores; the service
    # returns an honest empty result when a store has no records.
    def list_events(self, project_id: str, experiment_id: str, *, after_seq: int = 0, limit: int = 100) -> tuple[list[TrainingEvent], bool]: ...
    def list_logs(self, project_id: str, experiment_id: str, *, after_seq: int = 0, limit: int = 100) -> tuple[list[LogEntry], bool]: ...
    def get_metrics(self, project_id: str, experiment_id: str, *, attempt: int, after_step: int | None = None) -> ExperimentMetrics: ...
    def list_artifacts(self, project_id: str, experiment_id: str, *, after_id: str | None = None, limit: int = 50) -> tuple[list[TrainingArtifact], bool]: ...
    def comparison_metrics(self, project_id: str, experiment_id: str, *, protocol_id: str, protocol_version: str) -> dict[str, float] | None: ...

    # Production repositories may expose the fenced worker protocol.  The
    # in-memory contract adapter intentionally omits these methods.
    def claim(self, message: WorkerMessage, *, lease_seconds: int | None = None) -> object | None: ...
    def finish(self, message: WorkerMessage, *, execution_token: str, fencing_token: int, status: str, result: CandidateResult | None = None, error: dict[str, Any] | None = None) -> bool: ...


class Clock(Protocol):
    def now(self) -> Any: ...


__all__ = [
    "CandidateRegistrationPort", "Clock", "ConfirmationPort", "DataVersionPort",
    "EvaluationProtocolPort", "FeatureVersionPort", "TemplateHandler",
    "TrainingRepository", "TrainingTemplateRegistry",
]
