"""Bounded artifact access for data-import validation and snapshots.

All content keys are generated by the server.  A database row is published
only after the object store has verified the exact bytes and digest.
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from typing import Any
from uuid import uuid4

from sqlalchemy import select
from sqlalchemy.orm import Session

from chrom_platform.artifact_core.models import Artifact
from chrom_platform.artifact_core.storage import ArtifactStore
from .errors import DataUnavailableError, DataValidationError

_SHA256 = re.compile(r"^[0-9a-f]{64}$")


def _is_sha256(value: str) -> bool:
    return _SHA256.fullmatch(value) is not None


@dataclass(frozen=True)
class VerifiedImportArtifact:
    artifact_id: str
    content: bytes
    sha256: str
    media_type: str


class SQLAlchemyImportArtifactPort:
    """Use a caller-owned session and a controlled artifact store."""

    def __init__(self, session: Session, store: ArtifactStore) -> None:
        if callable(session) or not hasattr(session, "scalar"):
            raise TypeError("SQLAlchemyImportArtifactPort requires a caller-owned Session")
        self.session = session
        self.store = store

    def read_input(self, project_id: str, artifact_id: str) -> VerifiedImportArtifact:
        row = self.session.scalar(
            select(Artifact).where(
                Artifact.id == artifact_id, Artifact.project_id == project_id
            )
        )
        if row is None or row.project_id != project_id or row.id != artifact_id or row.status != "AVAILABLE" or row.scan_status != "PASSED":
            raise DataUnavailableError("输入制品不可用或尚未通过扫描")
        try:
            content = self.store.read(row.storage_key)
        except Exception as exc:
            raise DataUnavailableError("输入制品内容暂不可用") from exc
        digest = hashlib.sha256(content).hexdigest()
        if len(content) != row.size_bytes or row.sha256 != digest:
            raise DataValidationError("输入制品内容哈希与持久化元数据不一致")
        return VerifiedImportArtifact(row.id, content, digest, row.media_type)

    def ensure_available(self, project_id: str, artifact_id: str) -> bool:
        """The import input gate also requires the persisted scanner result."""
        self.read_input(project_id, artifact_id)
        return True

    def publish_generated(
        self,
        *,
        project_id: str,
        owner_id: str,
        kind: str,
        title: str,
        media_type: str,
        content: bytes,
        source_ref: dict[str, str],
        generation: str,
    ) -> tuple[str, str, int, str]:
        """Stage verified bytes and add AVAILABLE metadata in the caller's txn.

        The filesystem and SQL database do not share a transaction.  If the
        SQL transaction rolls back, the unreferenced server object is left for
        the artifact store's normal orphan cleanup.
        """
        if not content or not project_id or not owner_id:
            raise DataValidationError("生成制品内容或项目上下文无效")
        if not isinstance(source_ref, dict) or set(source_ref) != {"type", "id"}:
            raise DataValidationError("生成制品来源引用无效")
        if not all(isinstance(value, str) and value for value in source_ref.values()):
            raise DataValidationError("生成制品来源引用无效")
        artifact_id = f"artifact_{uuid4().hex}"
        expected_sha = hashlib.sha256(content).hexdigest()
        try:
            storage_key, size, digest = self.store.put(
                artifact_id, content, expected_size=len(content), expected_sha256=expected_sha
            )
        except Exception as exc:
            raise DataUnavailableError("生成制品暂时无法保存") from exc
        if size != len(content) or digest != expected_sha or not _SHA256.fullmatch(digest):
            raise DataValidationError("制品存储器返回的大小或哈希不匹配")
        self.session.add(Artifact(
            id=artifact_id,
            project_id=project_id,
            kind=kind,
            title=title,
            media_type=media_type,
            size_bytes=size,
            sha256=digest,
            storage_key=storage_key,
            status="AVAILABLE",
            # Server-generated JSON is never represented as user-scanned.
            scan_status="NOT_CONFIGURED",
            metadata_json={"source_ref": source_ref, "generation": generation},
            created_by=owner_id,
        ))
        self.session.flush()
        return artifact_id, storage_key, size, digest


class DataImportArtifactReadPolicy:
    """Restrict public import reports to their immutable validation record."""

    def __init__(self, session_factory, *, delegate: Any | None = None) -> None:
        self.session_factory = session_factory
        self.delegate = delegate

    def _validation(self, artifact: Artifact):
        metadata = artifact.metadata_json if isinstance(artifact.metadata_json, dict) else {}
        source = metadata.get("source_ref")
        if not isinstance(source, dict) or source.get("type") != "data_import_validation":
            return None
        validation_id = source.get("id")
        if not isinstance(validation_id, str) or not validation_id or len(validation_id) > 96:
            return None
        from .persistence import DataImportValidationRow
        with self.session_factory() as session:
            row = session.scalar(select(DataImportValidationRow).where(
                DataImportValidationRow.id == validation_id,
                DataImportValidationRow.project_id == artifact.project_id,
                DataImportValidationRow.report_artifact_id == artifact.id,
                DataImportValidationRow.status.in_(("VALID", "INVALID", "STALE")),
            ))
            if row is None:
                return None
            session.expunge(row)
            return row

    def _binding_matches(self, artifact: Artifact, validation: Any) -> bool:
        from .persistence import DataImportRow
        metadata = artifact.metadata_json if isinstance(artifact.metadata_json, dict) else {}
        binding = metadata.get("validation_binding")
        if not isinstance(binding, dict) or set(binding) != {
            "revision", "config_hash", "source_artifact_id", "source_sha256", "parser_hash",
        }:
            return False
        source_artifact_id = binding.get("source_artifact_id")
        source_sha256 = binding.get("source_sha256")
        parser_hash = binding.get("parser_hash")
        if (
            not isinstance(binding.get("revision"), int) or isinstance(binding.get("revision"), bool)
            or binding["revision"] < 1
            or not isinstance(binding.get("config_hash"), str) or not _is_sha256(binding["config_hash"])
            or not isinstance(source_artifact_id, str) or not source_artifact_id or len(source_artifact_id) > 96
            or not isinstance(source_sha256, str) or not _is_sha256(source_sha256)
            or not isinstance(parser_hash, str) or not _is_sha256(parser_hash)
        ):
            return False
        with self.session_factory() as session:
            data_import = session.scalar(select(DataImportRow).where(
                DataImportRow.id == validation.import_id,
                DataImportRow.project_id == artifact.project_id,
            ))
            source_artifact = session.scalar(select(Artifact).where(
                Artifact.id == source_artifact_id,
                Artifact.project_id == artifact.project_id,
            ))
            return bool(
                data_import is not None
                and source_artifact is not None
                and source_artifact.status == "AVAILABLE"
                and source_artifact.scan_status == "PASSED"
                and source_artifact.size_bytes > 0
                and metadata.get("validation_binding") == {
                    "revision": validation.revision,
                    "config_hash": validation.config_hash,
                    "source_artifact_id": source_artifact_id,
                    "source_sha256": source_artifact.sha256,
                    "parser_hash": validation.parser_hash,
                }
            )

    @staticmethod
    def _report_status_matches(validation_status: str, report_status: str) -> bool:
        if validation_status == "VALID":
            return report_status == "VALID"
        if validation_status == "INVALID":
            return report_status in {"INVALID", "UNAVAILABLE", "UNSUPPORTED_IMPORT_MODE"}
        if validation_status == "STALE":
            return report_status in {"VALID", "INVALID", "UNAVAILABLE", "UNSUPPORTED_IMPORT_MODE"}
        return False

    def can_read_export(self, artifact: Artifact, actor: Any) -> bool:
        metadata = artifact.metadata_json if isinstance(artifact.metadata_json, dict) else {}
        source = metadata.get("source_ref")
        if isinstance(source, dict) and source.get("type") == "data_import_validation":
            validation = self._validation(artifact)
            return bool(
                actor.can_access_project(artifact.project_id)
                and actor.can("data:read")
                and actor.can("artifact:read")
                and artifact.kind == "export_report"
                and artifact.status == "AVAILABLE"
                and artifact.scan_status == "NOT_CONFIGURED"
                and artifact.media_type == "application/json"
                and metadata.get("generation") == "data_import_validation_report_v1"
                and validation is not None
                and self._binding_matches(artifact, validation)
            )
        delegate = self.delegate
        return bool(delegate is not None and delegate.can_read_export(artifact, actor))

    def validate_export_body(self, artifact: Artifact, actor: Any, content: bytes) -> bool:
        metadata = artifact.metadata_json if isinstance(artifact.metadata_json, dict) else {}
        source = metadata.get("source_ref")
        if isinstance(source, dict) and source.get("type") == "data_import_validation":
            if len(content) > 2 * 1024 * 1024 or not self.can_read_export(artifact, actor):
                return False
            try:
                from .import_report import CsvImportValidationReport
                from .persistence import DataImportValidationRow, DataImportRow
                report = CsvImportValidationReport.model_validate_json(content)
                binding = metadata.get("validation_binding")
                if not isinstance(binding, dict):
                    return False
                with self.session_factory() as session:
                    validation = session.scalar(select(DataImportValidationRow).where(
                        DataImportValidationRow.id == source.get("id"),
                        DataImportValidationRow.project_id == artifact.project_id,
                        DataImportValidationRow.report_artifact_id == artifact.id,
                        DataImportValidationRow.status.in_(("VALID", "INVALID", "STALE")),
                    ))
                    data_import = session.scalar(select(DataImportRow).where(
                        DataImportRow.id == (validation.import_id if validation is not None else None),
                        DataImportRow.project_id == artifact.project_id,
                    ))
                    source_artifact = session.scalar(select(Artifact).where(
                        Artifact.id == binding.get("source_artifact_id"),
                        Artifact.project_id == artifact.project_id,
                    ))
                    return bool(
                        validation is not None and data_import is not None
                        and report.project_id == artifact.project_id == data_import.project_id
                        and report.import_id == validation.import_id == data_import.id
                        and report.revision == validation.revision
                        and report.config_hash == validation.config_hash
                        and report.domain_id == data_import.domain_id
                        and report.source_artifact_id == binding.get("source_artifact_id")
                        and binding == {
                            "revision": validation.revision,
                            "config_hash": validation.config_hash,
                            "source_artifact_id": report.source_artifact_id,
                            "source_sha256": report.source_sha256,
                            "parser_hash": validation.parser_hash,
                        }
                        and source_artifact is not None
                        and source_artifact.status == "AVAILABLE"
                        and source_artifact.scan_status == "PASSED"
                        and source_artifact.size_bytes > 0
                        and source_artifact.sha256 == report.source_sha256
                        and artifact.kind == "export_report"
                        and artifact.scan_status == "NOT_CONFIGURED"
                        and self._report_status_matches(validation.status, report.status)
                        and report.counts.model_dump(mode="json") == validation.counts
                        and artifact.media_type == "application/json"
                    )
            except (TypeError, ValueError, KeyError, json.JSONDecodeError):
                return False
        delegate = self.delegate
        validator = getattr(delegate, "validate_export_body", None)
        return bool(callable(validator) and validator(artifact, actor, content))


__all__ = ["DataImportArtifactReadPolicy", "SQLAlchemyImportArtifactPort", "VerifiedImportArtifact"]
