import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const frontendRoot = resolve(scriptDir, '..')
const buildsRoot = resolve(frontendRoot, '..', 'builds')
const args = process.argv.slice(2)
const argument = (name, fallback) => {
  const index = args.indexOf(name)
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback
}
const profile = argument('--profile', process.env.VITE_BUILD_PROFILE || 'universal-v1')
const output = resolve(frontendRoot, argument('--output', 'src/app/generated/registry.ts'))
const manifestOutput = resolve(frontendRoot, argument('--manifest-output', 'src/app/generated/build-manifest.json'))
const profileOutput = resolve(frontendRoot, argument('--profile-output', 'src/app/generated/profile.ts'))
const verify = args.includes('--verify')
const manifestPath = resolve(argument('--manifest', resolve(buildsRoot, `${profile}.json`)))
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
const validModules = new Set(['prediction', 'records', 'datasets', 'knowledge', 'training', 'model_center', 'utilities', 'assistant', 'settings'])
const modules = manifest.modules
if (!Array.isArray(modules) || modules.some((id) => !validModules.has(id))) throw new Error(`Invalid module list for ${profile}`)

const variableNames = { model_center: 'modelCenterModule' }
const variableFor = (id) => variableNames[id] || `${id}Module`
const moduleImports = modules.map((id) => `import { ${variableFor(id)} } from '@/modules/${id}/module'`)
const moduleValues = modules.map(variableFor)
const hasTlc = manifest.chromatography_types?.includes('tlc')
const hasTlcReverse = hasTlc && (manifest.prediction_tools?.tlc?.includes('reverse_solvent') || manifest.utilities?.includes('tlc_reverse_solvent'))
const hasUtilityTlcReverse = hasTlc && manifest.utilities?.includes('tlc_reverse_solvent')
const extensionImports = []
const extensionValues = []
if (hasTlc && modules.includes('prediction')) { extensionImports.push("import { predictionTlcExtension } from '@/modules/prediction/tlc-entry'"); extensionValues.push('predictionTlcExtension') }
if (hasTlcReverse && modules.includes('prediction') && manifest.prediction_tools?.tlc?.includes('reverse_solvent')) { extensionImports.push("import { predictionTlcReverseExtension } from '@/modules/prediction/tlc-reverse-entry'"); extensionValues.push('predictionTlcReverseExtension') }
if (hasUtilityTlcReverse && modules.includes('utilities')) { extensionImports.push("import { utilitiesTlcReverseExtension } from '@/modules/utilities/tlc-reverse-entry'"); extensionValues.push('utilitiesTlcReverseExtension') }
const batchExtensionNames = { tlc: 'predictionBatchTlcExtension', cc: 'predictionBatchCcExtension', hplc: 'predictionBatchHplcExtension', gc: 'predictionBatchGcExtension', sfc: 'predictionBatchSfcExtension' }
const batchTypes = ['tlc', 'cc', 'hplc', 'gc', 'sfc'].filter((type) => modules.includes('prediction') && manifest.chromatography_types?.includes(type) && manifest.prediction_tools?.[type]?.includes('batch'))
if (batchTypes.length) {
  const names = batchTypes.map((type) => batchExtensionNames[type])
  extensionImports.push(`import { ${names.join(', ')} } from '@/modules/prediction/batch-entry'`)
  extensionValues.push(...names)
}
const source = `/** Generated by scripts/generate-registry.mjs for ${profile}. Do not add runtime module discovery. */
import type { FrontendModule, FrontendModuleExtension } from '@/app/module'
${moduleImports.join('\n')}
${extensionImports.join('\n')}

export const generatedBuildId = '${profile}' as const
export const frontendModules: readonly FrontendModule[] = [${moduleValues.join(', ')}]
export const frontendExtensions: readonly FrontendModuleExtension[] = [${extensionValues.join(', ')}]
const registrations = [...frontendModules, ...frontendExtensions]
export const navigationRegistry = registrations.flatMap((entry) => entry.navigation).sort((left, right) => left.order - right.order)
export const routeRegistry = registrations.flatMap((entry) => entry.routes)
`

mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, source, 'utf8')
mkdirSync(dirname(manifestOutput), { recursive: true })
writeFileSync(manifestOutput, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')
mkdirSync(dirname(profileOutput), { recursive: true })
const assistantModes = manifest.assistant_features || []
writeFileSync(profileOutput, `/** Generated by scripts/generate-registry.mjs for ${profile}. */\nimport type { BuildProfile } from '@/app/profile'\n\nexport const activeProfile: BuildProfile = {\n  id: '${profile}',\n  modules: ${JSON.stringify(modules)},\n  chromatographyTypes: ${JSON.stringify(manifest.chromatography_types || [])},\n  predictionTools: ${JSON.stringify(manifest.prediction_tools || {})},\n  utilityFeatures: ${JSON.stringify(manifest.utilities || [])},\n  assistantModes: ${JSON.stringify(assistantModes)},\n}\n`, 'utf8')

if (verify) {
  const importedModules = [...source.matchAll(/@\/modules\/([^/]+)\/module/g)].map((match) => match[1]).sort()
  const expectedModules = [...modules].sort()
  if (JSON.stringify(importedModules) !== JSON.stringify(expectedModules)) throw new Error(`Registry imports ${importedModules.join(',')} but manifest selects ${expectedModules.join(',')}`)
  const importsTlc = source.includes("@/modules/prediction/tlc-entry")
  if (importsTlc !== Boolean(hasTlc && modules.includes('prediction'))) throw new Error(`TLC registry mismatch for ${profile}`)
  const importsPredictionReverse = source.includes("@/modules/prediction/tlc-reverse-entry")
  if (importsPredictionReverse !== Boolean(hasTlc && modules.includes('prediction') && manifest.prediction_tools?.tlc?.includes('reverse_solvent'))) throw new Error(`TLC prediction reverse registry mismatch for ${profile}`)
  const importsUtilityTlc = source.includes("@/modules/utilities/tlc-reverse-entry")
  if (importsUtilityTlc !== Boolean(hasUtilityTlcReverse && modules.includes('utilities'))) throw new Error(`TLC utility registry mismatch for ${profile}`)
  if (source.includes("@/modules/prediction/batch-entry") !== Boolean(batchTypes.length)) throw new Error(`Batch prediction registry mismatch for ${profile}`)
  for (const [type, name] of Object.entries(batchExtensionNames)) {
    if (source.includes(name) !== batchTypes.includes(type)) throw new Error(`Batch prediction route mismatch for ${profile}: ${type}`)
  }
  if (source.includes('import.meta.glob') || /import\s*\(/.test(source)) throw new Error('Registry must use explicit static imports')
  console.log(`registry ok: ${profile}`)
}
