import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const frontendRoot = resolve(scriptDir, '..')
const contractsRoot = resolve(frontendRoot, '..', 'contracts')
const indexPath = resolve(contractsRoot, 'index.json')
const freezePath = resolve(frontendRoot, '..', 'docs', 'V1_M3_M4_CONTRACT_FREEZE.json')
const outputRoot = resolve(frontendRoot, 'src/generated/contracts')
const args = process.argv.slice(2)
const arg = (name, fallback) => {
  const index = args.indexOf(name)
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback
}
const selectedProfile = arg('--profile', null)
const selectedOutputRoot = resolve(frontendRoot, arg('--output-root', 'src/generated/contracts'))
const verify = args.includes('--verify')
const httpMethods = new Set(['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'])

const index = JSON.parse(readFileSync(indexPath, 'utf8'))
const freeze = JSON.parse(readFileSync(freezePath, 'utf8'))
const profiles = Object.entries(index.contracts)
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([id, entry]) => ({ id, entry }))
if (selectedProfile && !index.contracts[selectedProfile]) throw new Error(`Unknown frozen contract profile: ${selectedProfile}`)
const targets = selectedProfile ? profiles.filter(({ id }) => id === selectedProfile) : profiles

const render = async (id, entry) => {
  const inputPath = resolve(contractsRoot, entry.path)
  const actualHash = createHash('sha256').update(readFileSync(inputPath)).digest('hex')
  if (actualHash !== entry.sha256) throw new Error(`${id} OpenAPI SHA-256 mismatch: ${actualHash} !== ${entry.sha256}`)
  const document = JSON.parse(readFileSync(inputPath, 'utf8'))
  const frozen = freeze.profiles.find((candidate) => candidate.profile === id)
  if (!frozen || String(frozen.normalized_openapi_sha256).toLowerCase() !== String(entry.sha256).toLowerCase()) throw new Error(`${id} M3/M4 normalized SHA does not match contracts/index.json`)
  const pathCount = Object.keys(document.paths ?? {}).length
  const operationCount = Object.values(document.paths ?? {}).reduce((count, pathItem) => count + Object.keys(pathItem).filter((method) => httpMethods.has(method.toLowerCase())).length, 0)
  if (!frozen || frozen.paths !== pathCount || frozen.operations !== operationCount) {
    throw new Error(`${id} M3/M4 freeze count mismatch: ${pathCount} paths/${operationCount} operations`)
  }
  // Preserve OpenAPI `required` as the sole source of TypeScript property
  // requiredness. openapi-typescript otherwise treats defaulted properties as
  // required by default, even when the schema lists them as optional.
  const generated = astToString(await openapiTS(document, { defaultNonNullable: false }))
  return `/**\n * Generated by openapi-typescript 7.13.0 from the frozen ${id} contract.\n * Input SHA-256: ${entry.sha256}\n * Do not edit manually; run npm run generate:contracts.\n */\n${generated}`
}

for (const { id, entry } of targets) {
  const destination = resolve(selectedOutputRoot, id, 'api-schema.ts')
  const source = await render(id, entry)
  mkdirSync(dirname(destination), { recursive: true })
  if (verify) {
    if (readFileSync(destination, 'utf8') !== source) throw new Error(`${id} generated contract is stale`)
  } else writeFileSync(destination, source, 'utf8')
}

const aliasProfile = selectedProfile || 'universal-v1'
const aliasPath = resolve(selectedOutputRoot, 'api-schema.ts')
const aliasSource = `/** Generated profile alias; staged packages replace this with their selected frozen contract. */\nexport type { components, operations, paths } from './${aliasProfile}/api-schema'\n`
if (verify) {
  if (readFileSync(aliasPath, 'utf8') !== aliasSource) throw new Error(`Generated contract alias is stale for ${aliasProfile}`)
} else {
  mkdirSync(dirname(aliasPath), { recursive: true })
  writeFileSync(aliasPath, aliasSource, 'utf8')
}

if (!selectedProfile && !verify) console.log(`generated frozen contracts: ${profiles.map(({ id }) => id).join(', ')}`)
if (verify) console.log(`frozen contract generation verified: ${targets.map(({ id }) => id).join(', ')}`)
